function WritePhreeqcSpeciesTable(outputDir, stepIndex, timeSeconds, grid, speciesData)
% WritePhreeqcSpeciesTable - Save triangle-wise PHREEQC chemistry output.

if ~exist(outputDir, 'dir')
    mkdir(outputDir);
end

numRows = grid.numT;
timestep = repmat(stepIndex, numRows, 1);
time_s = repmat(timeSeconds, numRows, 1);
triangle = (1:numRows)';
x_cm = grid.baryT(:, 1);
y_cm = grid.baryT(:, 2);

T = table(timestep, time_s, triangle, x_cm, y_cm);
fields = {'h_mol_cm3', 'h_activity_mol_cm3', 'ca_mol_cm3', 'hco3_mol_cm3', 'co3_mol_cm3', ...
    'cl_mol_cm3', 'na_mol_cm3', 'ca_total_mol_cm3', 'c_total_mol_cm3', ...
    'cl_total_mol_cm3', 'na_total_mol_cm3', 'pH', 'chargeBalance', ...
    'phreeqcPercentError', 'ionicStrength_mol_kgw', 'solutionWaterMass_kg', ...
    'specificConductance_uS_cm', 'fluidConductivity_S_m', ...
    'h_log10_activity', 'ca_log10_activity', 'hco3_log10_activity', ...
    'co3_log10_activity', 'cl_log10_activity', 'na_log10_activity', ...
    'h_activity_dimensionless', 'ca_activity_dimensionless', ...
    'hco3_activity_dimensionless', 'co3_activity_dimensionless', ...
    'cl_activity_dimensionless', 'na_activity_dimensionless', ...
    'water_volume_cm3', 'interface_area_cm2', 'calcite_moles', ...
    'calciteSI', 'calciteRate_mol_s', 'calciteKinDeltaRate_mol_s', ...
    'calciteRawKinDeltaRate_mol_s', 'calciteRawKineticDeltaMoles', ...
    'calciteRawUserPunchDeltaMoles', 'calciteRawUserPunchRate_mol_s', ...
    'calciteKineticReactantMoles', ...
    'calciteRatePerArea_mol_cm2_s', ...
    'interfaceCandidateRatePerArea_mol_cm2_s', 'calciteDissolvedMoles', ...
    'water_phase_h_delta_moles', 'water_phase_ca_delta_moles', ...
    'water_phase_c_delta_moles', 'water_phase_na_delta_moles', ...
    'water_phase_cl_delta_moles', 'calcite_ca_stoich_residual_moles', ...
    'calcite_c_stoich_residual_moles', ...
    'interfaceCandidateCalciteMoles', 'interfaceRealizedCalciteMoles', ...
    'interfacePrescribedCalciteMoles', 'projectedPrescribedCalciteMoles', ...
    'interfaceInventoryLimited'};
for iField = 1:numel(fields)
    fieldName = fields{iField};
    if isfield(speciesData, fieldName)
        T.(fieldName) = speciesData.(fieldName)(:);
    end
end

writetable(T, fullfile(outputDir, sprintf('phreeqc_species_%04d.csv', stepIndex)));
end
